// Teste da API: login, carga, gravação, conflito de versão, exclusão, permissões e cursor de mudanças.
// Uso: SENHA_ADMIN=... node api_test.mjs [url-base] [cookie-de-acesso-opcional]
import crypto from 'node:crypto';
const BASE = process.argv[2] || 'http://localhost:8787';
const EXTRA = process.argv[3] ? { Cookie: process.argv[3] } : {};
const sha = m => crypto.createHash('sha256').update(m, 'utf8').digest('hex');
let falhas = 0;
const ok = (cond, msg) => { console.log((cond ? 'OK   ' : 'FALHA') + ' ' + msg); if (!cond) falhas++; };
const j = async (r) => ({ status: r.status, corpo: await r.json().catch(() => ({})) });
const get = (p, t) => fetch(BASE + p, { headers: { ...EXTRA, ...(t ? { Authorization: 'Bearer ' + t } : {}) } }).then(j);
const post = (p, b, t) => fetch(BASE + p, { method: 'POST', headers: { ...EXTRA, 'Content-Type': 'application/json', ...(t ? { Authorization: 'Bearer ' + t } : {}) }, body: JSON.stringify(b) }).then(j);
const hash = (s, salt) => { let h = sha(salt + '|' + s + '|PRODUCAO-V7'); for (let i = 0; i < 500; i++) h = sha(h + salt); return h; };

const senha = process.env.SENHA_ADMIN;
const SUF = Date.now().toString(36);
let r = await post('/api/auth', { acao: 'login', email: 'admin@fabrica.com', senha: 'errada-' + SUF });
ok(r.status === 401, 'senha errada é recusada');
r = await get('/api/db?acao=mudancas&desde=0');
ok(r.status === 401, 'API sem sessão é recusada');
r = await post('/api/auth', { acao: 'login', email: 'admin@fabrica.com', senha });
ok(r.status === 200 && r.corpo.token, 'login do admin');
const T = r.corpo.token;
r = await get('/api/db?acao=tabela&tabela=USUARIOS', T);
ok(r.status === 200 && r.corpo.registros.length >= 3 && !r.corpo.registros.some(x => 'senhaHash' in x.dados), 'usuários carregados sem hash de senha');
r = await get('/api/db?acao=tabela&tabela=PRODUTOS', T);
const totalProd = r.corpo.registros.length;
ok(totalProd >= 72, 'carga de produtos (' + totalProd + ')');
const seq0 = r.corpo.seq;
// cria um produto de teste para não mexer nos reais
const idT = 'PROD-TESTE-' + SUF;
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'PRODUTOS', id: idT, base: 0, dados: { id: idT, nome: 'TESTE A', precoVenda: 1, status: 'INATIVO' } }] }, T);
ok(r.corpo.resultados[0].ok && r.corpo.resultados[0].versao === 1, 'inclusão aceita (versão 1)');
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'PRODUTOS', id: idT, base: 1, dados: { id: idT, nome: 'ALTERADO A', precoVenda: 1, status: 'INATIVO' } }] }, T);
ok(r.corpo.resultados[0].ok && r.corpo.resultados[0].versao === 2, 'alteração aceita e versão incrementada');
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'PRODUTOS', id: idT, base: 1, dados: { id: idT, nome: 'ALTERADO B' } }] }, T);
ok(!r.corpo.resultados[0].ok && r.corpo.resultados[0].atual.dados.nome === 'ALTERADO A', 'gravação com versão velha vira conflito e devolve o registro atual');
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'CATEGORIAS', id: 'CAT-TESTE-' + SUF, base: 0, dados: { nome: 'Teste' } }, { op: 'delete', tabela: 'PRODUTOS', id: idT }] }, T);
ok(r.corpo.resultados.every(x => x.ok), 'inclusão e exclusão no mesmo lote');
r = await get('/api/db?acao=mudancas&desde=' + seq0, T);
ok(r.corpo.alterados.some(x => x.id === 'CAT-TESTE-' + SUF) && r.corpo.excluidos.some(x => x.id === idT), 'cursor devolve inclusão e exclusão');
ok(!r.corpo.alterados.some(x => x.id === idT), 'registro excluído não volta como alterado');
r = await get('/api/db?acao=tabela&tabela=PRODUTOS', T);
ok(r.corpo.registros.length === totalProd, 'exclusão é permanente');
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'PRODUTOS', id: idT, base: 2, dados: { id: idT, nome: 'X' } }] }, T);
ok(!r.corpo.resultados[0].ok && r.corpo.resultados[0].motivo === 'excluido', 'editar registro excluído por outro usuário é recusado');
const emailOp = 'op-' + SUF + '@teste.local', idOp = 'USR-TESTE-' + SUF;
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'USUARIOS', id: idOp, base: 0, dados: { id: idOp, nome: 'Op', email: emailOp, perfil: 'PRODUCAO', status: 'ATIVO', senhaSalt: 's', senhaHash: hash('abc123', 's'), precisaTrocarSenha: false } }] }, T);
ok(r.corpo.resultados[0].ok, 'admin cria usuário com senha');
r = await post('/api/auth', { acao: 'login', email: emailOp, senha: 'abc123' });
ok(r.status === 200, 'novo usuário entra');
const T2 = r.corpo.token;
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'USUARIOS', id: idOp, base: 1, dados: { id: idOp, perfil: 'ADMIN' } }] }, T2);
ok(!r.corpo.resultados[0].ok && r.corpo.resultados[0].motivo === 'permissao', 'operador não consegue se promover a admin');
r = await get('/api/db?acao=tabela&tabela=USUARIOS', T);
let novo = r.corpo.registros.find(x => x.id === idOp);
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'USUARIOS', id: idOp, base: novo.versao, dados: { ...novo.dados, nome: 'Operador 2' } }] }, T);
ok(r.corpo.resultados[0].ok, 'admin edita usuário sem reenviar a senha');
r = await post('/api/auth', { acao: 'login', email: emailOp, senha: 'abc123' });
ok(r.status === 200, 'senha preservada após a edição');
r = await get('/api/db?acao=tabela&tabela=USUARIOS', T);
novo = r.corpo.registros.find(x => x.id === idOp);
r = await post('/api/db', { ops: [{ op: 'upsert', tabela: 'USUARIOS', id: idOp, base: novo.versao, dados: { ...novo.dados, status: 'BLOQUEADO' } }] }, T);
ok(r.corpo.resultados[0].ok, 'admin bloqueia o usuário');
r = await get('/api/db?acao=mudancas&desde=0', T2);
ok(r.status === 401, 'usuário bloqueado perde o acesso na hora');
r = await get('/api/db?acao=status', T);
ok(r.status === 200 && r.corpo.porTabela.length > 5, 'status do banco para o admin');
// limpeza dos registros de teste
r = await post('/api/db', { ops: [{ op: 'delete', tabela: 'USUARIOS', id: idOp }, { op: 'delete', tabela: 'CATEGORIAS', id: 'CAT-TESTE-' + SUF }] }, T);
ok(r.corpo.resultados.every(x => x.ok), 'limpeza dos registros de teste');
console.log(falhas ? falhas + ' FALHA(S)' : 'TODOS OS TESTES PASSARAM');
process.exit(falhas ? 1 : 0);
